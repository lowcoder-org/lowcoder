import static org.lowcoder.plugin.sql.GeneralSqlExecutorStatementTest.KEYS_FAILURE_TEXT;
import static org.lowcoder.plugin.sql.GeneralSqlExecutorStatementTest.ONE_ROW;
import static org.lowcoder.plugin.sql.GeneralSqlExecutorStatementTest.OTHER_STATE;
import static org.lowcoder.plugin.sql.GeneralSqlExecutorStatementTest.QUERY_FAILURE_STATE;
import static org.lowcoder.plugin.sql.GeneralSqlExecutorStatementTest.TABLE;
