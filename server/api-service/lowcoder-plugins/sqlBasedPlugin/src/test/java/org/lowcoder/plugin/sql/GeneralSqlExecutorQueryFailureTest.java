/**
 * NEW-9: {@link GeneralSqlExecutor#isQueryFailure} decides whether an exception of {@code getGeneratedKeys} fails the query.
 * An executor that names one SQL state a failure fails the query with that exception, prepared, plain and GUI, and closes
 * the statement; any other {@link SQLException} and any non-SQL exception still mean "no keys". On H2, with the statement's
 * {@code getGeneratedKeys} made to throw by {@link GeneralSqlExecutorStatementTest#keysFailWith}.
 */
public class GeneralSqlExecutorQueryFailureTest {

    private static final String URL = H2SqlTestSupport.newUrl("queryfailure");
    private static Connection connection;

    /** Names {@link GeneralSqlExecutorStatementTest#QUERY_FAILURE_STATE} a query failure, nothing else. */
    private static final GeneralSqlExecutor EXECUTOR = new GeneralSqlExecutor() {
        @Override
        protected boolean isQueryFailure(SQLException e) {
            return QUERY_FAILURE_STATE.equals(e.getSQLState());
        }
    };

    @BeforeAll
    static void open() {
        connection = H2SqlTestSupport.open(URL);
    }

    @AfterAll
    static void close() throws Exception {
        connection.close();
    }

    /** The table of {@link GeneralSqlExecutorStatementTest}, which its GUI insert writes, in this class's own database. */
    @BeforeEach
    void freshTable() {
        H2SqlTestSupport.run(connection, "drop table if exists " + TABLE,
                "create table " + TABLE + " (id bigint generated by default as identity, v varchar(50))");
    }

    private static SqlBasedQueryExecutionContext sql(boolean plain) {
        return SqlBasedQueryExecutionContext.builder().query(INSERT_A).requestParams(Map.of()).disablePreparedStatement(plain).build();
    }

    /** The three ways a statement is made: prepared SQL, plain SQL and a GUI insert (prepared with generated keys). */
    private static final Map<String, Function<Connection, QueryExecutionResult>> MODES = Map.of(
            "prepared", target -> EXECUTOR.execute(target, sql(false)),
            "plain", target -> EXECUTOR.execute(target, sql(true)),
            "gui", target -> runGui(EXECUTOR, target, true));

    @Test
    public void aQueryFailureOfGetGeneratedKeysFailsTheQueryWhenTheExecutorSaysSoNEW9() throws Exception {
        for (Map.Entry<String, Function<Connection, QueryExecutionResult>> mode : MODES.entrySet()) {
            List<Statement> handedOut = new ArrayList<>();
            Connection failing = keysFailWith(connection, new SQLException(KEYS_FAILURE_TEXT, QUERY_FAILURE_STATE), handedOut);
            PluginException thrown = assertPluginError(QUERY_EXECUTION_ERROR, H2SqlTestSupport.QUERY_ERROR_KEY, () -> mode.getValue().apply(failing));
            System.out.println("[GeneralSqlExecutorQueryFailureTest] " + mode.getKey() + ": query failure -> " + thrown.getMessage());
            assertTrue(thrown.getMessage().contains(KEYS_FAILURE_TEXT), mode.getKey() + ": " + thrown.getMessage());
            assertEquals(1, handedOut.size(), mode.getKey());
            assertTrue(handedOut.get(0).isClosed(), mode.getKey() + ": the executor closed the statement");

            for (Exception noKeys : List.of(new SQLException(KEYS_FAILURE_TEXT, OTHER_STATE), new IllegalStateException(KEYS_FAILURE_TEXT))) {
                QueryExecutionResult result = mode.getValue().apply(keysFailWith(connection, noKeys, new ArrayList<>()));
                System.out.println("[GeneralSqlExecutorQueryFailureTest] " + mode.getKey() + ": " + noKeys.getClass().getSimpleName()
                        + " -> " + result.getData());
                assertEquals(ONE_ROW, result.getData(), mode.getKey() + ", " + noKeys);
            }
        }
    }
}
