// Emit crawler-readable metadata into the HTML; social crawlers do not need JS.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const origin = 'https://sdk.lowcoder.cloud';
const metadata = require('../seo.json');
const images = require('../social-images.json');
const escape = value => value.replace(/[&<>"']/g, char => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[char]);

for (const [route, meta] of Object.entries(metadata)) {
  if (!images[meta.card] || !fs.existsSync(path.join(root, 'site', images[meta.card]))) {
    throw new Error(`Missing social preview for ${route}`);
  }
  const url = origin + route;
  const image = origin + images[meta.card];
  const tag = (key, value, property = false) => `    <meta ${property ? 'property' : 'name'}="${key}" content="${escape(value)}" />`;
  const schema = {
    '@context': 'https://schema.org',
    '@graph': [
      { '@type': 'Organization', '@id': 'https://www.lowcoder.cloud/#organization', name: 'Lowcoder', url: 'https://www.lowcoder.cloud/', sameAs: ['https://github.com/lowcoder-org/lowcoder'] },
      { '@type': 'WebSite', '@id': `${origin}/#website`, name: 'Lowcoder SDK', url: `${origin}/`, inLanguage: 'en', publisher: { '@id': 'https://www.lowcoder.cloud/#organization' } },
      { '@type': 'ImageObject', '@id': `${url}#primaryimage`, url: image, contentUrl: image, width: 1200, height: 630, encodingFormat: 'image/png', caption: meta.imageAlt },
      { '@type': 'WebPage', '@id': url, url, name: meta.title, description: meta.description, inLanguage: 'en', isPartOf: { '@id': `${origin}/#website` }, primaryImageOfPage: { '@id': `${url}#primaryimage` } },
    ],
  };
  const block = [
    '    <!-- SEO: generated by scripts/prepare-site.cjs from seo.json -->',
    `    <title>${escape(meta.title)}</title>`,
    tag('description', meta.description),
    `    <link rel="canonical" href="${url}" />`,
    '    <link rel="sitemap" type="application/xml" href="/sitemap.xml" />',
    tag('robots', 'index, follow, max-image-preview:large'),
    ...Object.entries({ type: 'website', site_name: 'Lowcoder SDK', locale: 'en_US', title: meta.title, description: meta.description, url, image, 'image:secure_url': image, 'image:type': 'image/png', 'image:width': '1200', 'image:height': '630', 'image:alt': meta.imageAlt }).map(([key, value]) => tag(`og:${key}`, value, true)),
    ...Object.entries({ card: 'summary_large_image', title: meta.title, description: meta.description, image, 'image:alt': meta.imageAlt }).map(([key, value]) => tag(`twitter:${key}`, value)),
    '    <script type="application/ld+json">',
    JSON.stringify(schema, null, 2).replace(/</g, '\\u003c').split('\n').map(line => `      ${line}`).join('\n'),
    '    </script>',
    '    <!-- /SEO -->',
  ].join('\n');
  const file = path.join(root, meta.file);
  let html = fs.readFileSync(file, 'utf8');
  const marker = html.includes('<!-- SEO:')
    ? /    <!-- SEO:[\s\S]*?    <!-- \/SEO -->/
    : /    <title>[\s\S]*?<meta name="theme-color"/;
  if (!marker.test(html)) throw new Error(`Cannot find metadata section in ${meta.file}`);
  if (html.includes('<!-- SEO:')) {
    html = html.replace(/    <!-- SEO:[\s\S]*?    <!-- \/SEO -->/, block);
  } else {
    html = html.replace(/    <title>[\s\S]*?<meta name="theme-color"/, `${block}\n    <meta name="theme-color"`);
  }
  fs.writeFileSync(file, html);
}

// Only index public content, not runtime assets or legacy component examples.
fs.writeFileSync(path.join(root, 'site/sitemap.xml'), `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${Object.keys(metadata).map(route => `  <url><loc>${origin}${route}</loc></url>`).join('\n')}\n</urlset>\n`);
fs.writeFileSync(path.join(root, 'site/robots.txt'), `User-agent: *\nAllow: /\n\nSitemap: ${origin}/sitemap.xml\n`);
console.log(`Prepared search and social metadata for ${Object.keys(metadata).length} SDK pages.`);
