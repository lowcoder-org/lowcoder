-- Data of the Firebird sidecar that run-in-docker.sh starts only with E2E_INCLUDE_NODE_SERVICE_SIDECARS=1. The image runs this file
-- once, with isql, when it creates the database /var/lib/firebird/data/e2e.fdb (see the FIREBIRD_* values of the script). Must equal FIREBIRD_ITEMS
-- in e2e/src/datasource/firebird.ts.

-- Read-only rows for the query tests. No test writes them. `NOTE` is NULL on the second row.
CREATE TABLE FB_ITEMS (
    ID INTEGER NOT NULL PRIMARY KEY,
    NAME VARCHAR(40) NOT NULL,
    PRICE NUMERIC(9, 2) NOT NULL,
    NOTE VARCHAR(40)
);
COMMIT;
INSERT INTO FB_ITEMS (ID, NAME, PRICE, NOTE) VALUES (1, 'alpha', 1.50, 'first');
INSERT INTO FB_ITEMS (ID, NAME, PRICE, NOTE) VALUES (2, 'beta', 2.25, NULL);
INSERT INTO FB_ITEMS (ID, NAME, PRICE, NOTE) VALUES (3, 'gamma', 10.00, 'third');
COMMIT;

-- Rows the write tests insert. Every test writes only rows with its own OWNER value, so tests running in parallel never see each
-- other's rows.
CREATE TABLE FB_NOTES (
    ID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    OWNER VARCHAR(80) NOT NULL,
    BODY VARCHAR(200) NOT NULL
);
CREATE INDEX FB_NOTES_OWNER_IDX ON FB_NOTES (OWNER);
COMMIT;
